// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// the pre-token protocols below the watchlist floor that pass the watchlist's own exclusion rule:
// no token recorded, not a wrapped / staked / bridged product, not an exchange, not a versioned
// pool. A protocol is pre-token when its record carries no token (no market cap, no CoinGecko id,
// no symbol); the snapshot's live-token protocols are kept apart and shown as the market's own
// values, never mixed into the ranked board. Say a protocol "records no token", never that it
// "has no token": the record is not proof.
//
// Implied value follows only from the snapshot's own figures, never from a hardcoded list of
// names. The category multiple is estimated from comparable protocols that already trade: for
// each category, the median market-cap-to-TVL ratio of the token-bearing protocols in that
// category, computed from this snapshot. A category with fewer than three token-bearing
// protocols falls back to the overall median. The multiple is clamped to [0.05, 2.0] so a thin
// category cannot stretch a value past sense.
//
//   multiple     = clamp(median(mcap_usd / tvl_usd over token-bearing peers in the category),
//                         0.05, 2.0)          (fallback: overall median, same clamp)
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x 0.5
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied      = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// A growing protocol earns a higher multiple; a shrinking one a lower one. A protocol that has
// run longer with no token recorded earns a fuller multiple, up to the three-year cap. The board
// is sorted by implied value, ties broken by slug so the output is byte-stable, and ranks run
// 1..N. No protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  /** Minimum token-bearing peers in a category before its own median is trusted. */
  min_peers: number;
  /** Floor and cap of the category multiple. */
  multiple_floor: number;
  multiple_cap: number;
  /** Weight of the 7-day growth adjustment. */
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  /** Maturity curve: floor, range, and the age in days at which it tops out. */
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  /** Age in days assumed when a protocol's listed_at is absent. */
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  min_peers: 3,
  multiple_floor: 0.05,
  multiple_cap: 2.0,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

